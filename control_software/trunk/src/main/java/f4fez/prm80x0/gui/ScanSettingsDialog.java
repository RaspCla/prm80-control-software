    private void okButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_okButtonActionPerformed
        int from;
        int to;
        int step;
        try {
            from = hz(this.fromField.getText(), 6);
            to = hz(this.toField.getText(), 6);
            step = hz(String.valueOf(this.stepComboBox.getSelectedItem()), 3);
        } catch (RuntimeException ex) {
            this.error("Please enter the frequencies in MHz (e.g. 145.0125) and the step in kHz (e.g. 12.5).");
            return;
        }
        if (step <= 0 || step % this.pllStep != 0) {
            this.error("The step must be a multiple of the PLL step (" + khz(this.pllStep) + " kHz).");
            return;
        }
        if (from <= 0 || to <= from) {
            this.error("\"To\" must be higher than \"From\".");
            return;
        }
        if (from % this.pllStep != 0 || to % this.pllStep != 0) {
            this.error("The frequencies must be multiples of the PLL step (" + khz(this.pllStep) + " kHz).");
            return;
        }
        if ((to - from) / step > 2000) {
            this.error("The range has more than 2000 steps - please choose a smaller range or a bigger step.");
            return;
        }
        this.config.setScanRange(this.band, from, to);
        this.config.setScanStep(step);
        this.config.setScanHold(((Number) this.holdSpinner.getValue()).intValue() * 1000);
        this.saved = true;
        this.dispose();
    }//GEN-LAST:event_okButtonActionPerformed

