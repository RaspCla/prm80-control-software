    /**
     * @param parent main window
     * @param band 144 or 430
     * @param pllStep PLL step of the PRM80 in Hz
     */
    public ScanSettingsDialog(java.awt.Frame parent, int band, int pllStep) {
        super(parent, true);
        this.config = new Option();
        this.band = band;
        this.pllStep = pllStep;
        initComponents();
        int[] range = range(this.config, band);
        this.fromField.setText(mhz(range[0]));
        this.toField.setText(mhz(range[1]));
        this.stepComboBox.setSelectedItem(khz(step(this.config, pllStep)));
        this.holdSpinner.setValue(Math.round(this.config.getScanHold() / 1000f));
        this.getRootPane().setDefaultButton(this.okButton);
        Zoom.install(this);
    }

    /** @return true if closed with OK (the settings are stored then) */
    public boolean isSaved() {
        return this.saved;
    }

    /** @return true if the VFO range was never set for this band */
    public static boolean isRangeUnset(Option config, int band) {
        return config.getScanFrom(band) == 0 || config.getScanTo(band) == 0;
    }

    /** @return {from, to} in Hz: stored values or defaults for the band */
    public static int[] range(Option config, int band) {
        int from = config.getScanFrom(band);
        int to = config.getScanTo(band);
        if (from == 0 || to == 0) {
            if (band == Controler.FREQ430) {
                from = 438650000;       // repeater outputs (DL)
                to = 439425000;
            } else {
                from = 145000000;       // FM simplex and repeater outputs
                to = 145800000;
            }
        }
        return new int[] {from, to};
    }

    /** @return step in Hz: stored value or the PLL step */
    public static int step(Option config, int pllStep) {
        int step = config.getScanStep();
        if (step <= 0 || step % pllStep != 0)
            step = pllStep;
        return step;
    }

    private static String mhz(int hz) {
        BigDecimal mhz = new BigDecimal(hz).movePointLeft(6).stripTrailingZeros();
        if (mhz.scale() < 3)
            mhz = mhz.setScale(3);         // 145.000
        return mhz.toPlainString();
    }

    private static String khz(int hz) {
        return new BigDecimal(hz).movePointLeft(3).stripTrailingZeros().toPlainString();
    }

    private static int hz(String value, int decimals) {
        return new BigDecimal(value.trim().replace(',', '.')).movePointRight(decimals).intValueExact();
    }

