    /** Writing to the PRM80, provided by the main window (background thread). */
    public interface MemoryAccess {
        /** Write one channel, then call done or error (GUI thread). */
        void writeChannel(Channel channel, Runnable done, Consumer<String> error);
        /** Remove the last channel, then call done or error (GUI thread). */
        void deleteLastChannel(Runnable done, Consumer<String> error);
    }

    /** One write, for "Undo" */
    private static class Change {
        final int number;
        final Channel before;   // null: the channel was added

        Change(int number, Channel before) {
            this.number = number;
            this.before = before;
        }
    }

