    private void tableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableMouseClicked
        if (evt.getClickCount() == 2 && this.table.getSelectedRow() >= 0)
            this.choose();
    }//GEN-LAST:event_tableMouseClicked

    /** Take the selected row, ask before an existing channel is replaced. */
    private void choose() {
        int row = this.table.getSelectedRow();
        if (row < 0)
            return;
        if (row < this.channels.countChannel()) {
            Channel c = this.channels.getChannel(row);
            String text = "Replace channel " + row + " (" + c.getFrequency() + " MHz";
            if (c.getComments() != null && !c.getComments().isEmpty())
                text += ", " + c.getComments();
            text += ")?";
            if (JOptionPane.showConfirmDialog(this, text, this.getTitle(),
                    JOptionPane.OK_CANCEL_OPTION, JOptionPane.QUESTION_MESSAGE) != JOptionPane.OK_OPTION)
                return;
        }
        this.selectedChannel = row;
        this.dispose();
    }

    /**
     * @return the chosen channel number (number of channels = new channel),
     * -1 if cancelled
     */
    public int getSelectedChannel() {
        return this.selectedChannel;
    }

    /** Read only view of the channels plus one row for a new channel. */
    private class MemoryModel extends AbstractTableModel {
        private static final long serialVersionUID = 1L;
        private final String[] names = {"Channel", "Frequency", "Shift Freq.", "Shift +/-", "Shift Enabled", "Scan Lock", "Comment"};

        @Override
        public int getRowCount() {
            return channels.countChannel() + 1;
        }

        @Override
        public int getColumnCount() {
            return names.length;
        }

        @Override
        public String getColumnName(int column) {
            return names[column];
        }

        @Override
        public Object getValueAt(int row, int column) {
            if (row == channels.countChannel()) {
                switch (column) {
                    case 0: return Integer.toString(row);
                    case 1: return "(new channel)";
                    default: return "";
                }
            }
            Channel c = channels.getChannel(row);
            switch (column) {
                case 0: return Integer.toString(row);
                case 1: return c.getFrequency();
                case 2: return c.getShiftFreq();
                case 3: return c.getShift();
                case 4: return c.getShiftEnabled();
                case 5: return c.getScanLock();
                default: return c.getComments();
            }
        }
    }

