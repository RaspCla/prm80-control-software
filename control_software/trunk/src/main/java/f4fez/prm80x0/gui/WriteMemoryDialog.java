    /** Write the VFO to the selected channel, the dialog stays open. */
    private void write() {
        final int row = this.table.getSelectedRow();
        if (row < 0 || this.busy)
            return;
        final boolean isNew = row >= this.channels.countChannel();
        if (!isNew) {
            Channel c = this.channels.getChannel(row);
            String text = "Replace channel " + row + " (" + c.getFrequency() + " MHz";
            if (c.getComments() != null && !c.getComments().isEmpty())
                text += ", " + c.getComments();
            text += ")?";
            if (JOptionPane.showConfirmDialog(this, text, this.getTitle(),
                    JOptionPane.OK_CANCEL_OPTION, JOptionPane.QUESTION_MESSAGE) != JOptionPane.OK_OPTION)
                return;
        }
        final Channel before = isNew ? null : this.channels.getChannel(row).copy();
        final Channel channel = this.vfo.copy();
        channel.setId(row);
        if (before != null)
            channel.setScanLock(before.getScanLock());   // keep the scan lock out of the channel
        channel.setComments(this.commentField.getText().trim());
        this.setBusy(true, "Writing channel " + row + " ...");
        this.access.writeChannel(channel, () -> {
            this.changes.push(new Change(row, before));
            ChannelManager.prmChannelWritten(channel);
            this.setBusy(false, "Channel " + row + " written" + (isNew ? " (new channel)" : ""));
            this.refreshTable(row);
        }, error -> this.setBusy(false, "Writing channel " + row + " failed: " + error));
    }

    /** Take back the last write: old channel back, or remove the added one. */
    private void undo() {
        if (this.changes.isEmpty() || this.busy)
            return;
        final Change change = this.changes.peek();
        if (change.before == null) {
            this.setBusy(true, "Removing channel " + change.number + " ...");
            this.access.deleteLastChannel(() -> {
                this.changes.pop();
                ChannelManager.prmLastChannelRemoved();
                this.setBusy(false, "Channel " + change.number + " removed again");
                this.refreshTable(Math.min(change.number, this.channels.countChannel()));
            }, error -> this.setBusy(false, "Undo failed: " + error));
        } else {
            this.setBusy(true, "Restoring channel " + change.number + " ...");
            this.access.writeChannel(change.before, () -> {
                this.changes.pop();
                ChannelManager.prmChannelWritten(change.before);
                this.setBusy(false, "Channel " + change.number + " restored");
                this.refreshTable(change.number);
            }, error -> this.setBusy(false, "Undo failed: " + error));
        }
    }

    private void close() {
        if (!this.busy)
            this.dispose();
    }

    private void refreshTable(int selectRow) {
        this.model.fireTableDataChanged();
        if (selectRow >= 0 && selectRow < this.table.getRowCount())
            this.table.setRowSelectionInterval(selectRow, selectRow);
    }

    private void setBusy(boolean busy, String message) {
        this.busy = busy;
        this.setCursor(busy ? Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR) : null);
        this.table.setEnabled(!busy);
        this.statusLabel.setText(message);
        this.updateButtons();
    }

    private void updateButtons() {
        this.writeButton.setEnabled(!this.busy && this.table.getSelectedRow() >= 0);
        this.undoButton.setEnabled(!this.busy && !this.changes.isEmpty());
        this.okButton.setEnabled(!this.busy);
        this.commentField.setEnabled(!this.busy);
    }

    /** Read only view of the channels plus one row for a new channel. */
    private class MemoryModel extends AbstractTableModel {
        private static final long serialVersionUID = 1L;
        private final String[] names = {"Channel", "Frequency", "Shift Freq.", "Shift +/-", "Shift Enabled", "Shift Reverse", "Scan Lock", "Comment"};

        @Override
        public int getRowCount() {
            // a new channel only if there is room (channels 0 to 99)
            return channels.countChannel() + (channels.countChannel() < ChannelList.MAX_CHANNELS ? 1 : 0);
        }

        @Override
        public int getColumnCount() {
            return names.length;
        }

        @Override
        public String getColumnName(int column) {
            return names[column];
        }

        @Override
        public Object getValueAt(int row, int column) {
            if (row >= channels.countChannel()) {
                switch (column) {
                    case 0: return Integer.toString(row);
                    case 1: return "(new channel)";
                    default: return "";
                }
            }
            Channel c = channels.getChannel(row);
            switch (column) {
                case 0: return Integer.toString(row);
                case 1: return c.getFrequency();
                case 2: return c.getShiftFreq();
                case 3: return c.getShift();
                case 4: return c.getShiftEnabled();
                case 5: return c.getShiftReverse();
                case 6: return c.getScanLock();
                default: return c.getComments();
            }
        }
    }

